// Generates src/lib/services.generated.ts from the mobile app's service catalogue, so the prices on the
// website's service pages can't drift from the app. Run: node apps/web/scripts/sync-services.js
const fs = require('fs')
const path = require('path')
const { loadMobileCatalogue } = require('../../api/test/helpers/mobile-catalogue')

const WANTED = ['plumbing', 'electrical', 'cleaning', 'handyman', 'pest_control', 'locksmith', 'hvac', 'pool']
const { SERVICES } = loadMobileCatalogue()

const out = {}
for (const id of WANTED) {
  const s = SERVICES.find(x => x.id === id)
  if (!s) throw new Error(`service ${id} missing from the catalogue`)
  const q = s.questions.find(x => x.type === 'select' && x.options && x.options.some(o => o.priceMax > 0))
  out[id] = {
    label: s.label,
    priceLabel: s.priceLabel,
    jobs: q.options.filter(o => o.priceMax > 0).map(o => ({ label: o.label, min: o.priceMin, max: o.priceMax })),
  }
}

const file = path.join(__dirname, '../src/lib/services.generated.ts')
fs.writeFileSync(file,
`// GENERATED by apps/web/scripts/sync-services.js from apps/mobile/lib/serviceConfig.ts — do not edit by hand.
export interface CatalogueJob { label: string; min: number; max: number }
export interface CatalogueService { label: string; priceLabel: string; jobs: CatalogueJob[] }

export const CATALOGUE: Record<string, CatalogueService> = ${JSON.stringify(out, null, 2)}
`)
console.log('wrote', file)
