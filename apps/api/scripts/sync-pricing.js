/**
 * Regenerates src/modules/bookings/pricing.generated.ts from the mobile app's service catalogue,
 * so the API can recompute a booking's price itself instead of trusting the amount the app sends.
 *
 *   pnpm --filter api sync:pricing
 *
 * test/pricing.spec.ts fails if the generated table drifts from apps/mobile/lib/serviceConfig.ts.
 */
const fs = require('fs')
const path = require('path')
const { loadMobileCatalogue } = require('../test/helpers/mobile-catalogue')

const OUT = path.join(__dirname, '../src/modules/bookings/pricing.generated.ts')
const { SERVICES } = loadMobileCatalogue()

const table = {}
for (const s of SERVICES) {
  table[s.id] = s.questions
    .filter(q => q.type === 'select' && Array.isArray(q.options))
    .map(q => ({
      key: q.key,
      options: q.options.map(o => ({ value: o.value, priceMin: o.priceMin, priceMax: o.priceMax })),
    }))
}

const body =
`// GENERATED by scripts/sync-pricing.js from apps/mobile/lib/serviceConfig.ts — do not edit by hand.
// Only the price-bearing "select" questions are kept. Re-run \`pnpm --filter api sync:pricing\` after changing prices.

export interface PricedOption { value: string; priceMin: number; priceMax: number }
export interface PricedQuestion { key: string; options: PricedOption[] }

export const SERVICE_PRICING: Record<string, PricedQuestion[]> = ${JSON.stringify(table, null, 2)}
`
fs.writeFileSync(OUT, body)
console.log(`Wrote ${Object.keys(table).length} services to ${path.relative(process.cwd(), OUT)}`)
